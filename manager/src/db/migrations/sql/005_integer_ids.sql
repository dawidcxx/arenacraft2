-- Convert accounts.id and realms.id from UUID to integer types to match the
-- Zig server (auth.zig / char.zig):
--   accounts.id         -> BIGINT
--   realms.id           -> SMALLINT
--   characters.account_id -> BIGINT
--   characters.realm_id   -> SMALLINT

DROP TABLE IF EXISTS character_equipment CASCADE;
DROP TABLE IF EXISTS characters CASCADE;
DROP TABLE IF EXISTS world_instances CASCADE;
DROP TABLE IF EXISTS realms CASCADE;
DROP TABLE IF EXISTS accounts CASCADE;

CREATE TABLE accounts (
    id BIGSERIAL PRIMARY KEY,
    username VARCHAR(16) NOT NULL,
    email VARCHAR(255),
    salt BYTEA NOT NULL,
    verifier BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_login_at TIMESTAMPTZ,
    last_ip INET,
    CONSTRAINT accounts_username_uppercase CHECK (username::text = UPPER(username::text)),
    CONSTRAINT accounts_username_len CHECK (CHAR_LENGTH(username::text) >= 2 AND CHAR_LENGTH(username::text) <= 16),
    CONSTRAINT accounts_salt_len CHECK (OCTET_LENGTH(salt) = 32),
    CONSTRAINT accounts_verifier_len CHECK (OCTET_LENGTH(verifier) = 32)
);

CREATE UNIQUE INDEX accounts_username_unique ON accounts (username);

CREATE TABLE realms (
    id SMALLINT PRIMARY KEY,
    realmname VARCHAR(32) NOT NULL
);

CREATE UNIQUE INDEX realms_realmname_key ON realms (realmname);

