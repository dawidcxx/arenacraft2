CREATE TABLE characters (
    id UUID DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
    guid BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    account_id BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    realm_id SMALLINT NOT NULL REFERENCES realms(id) ON DELETE CASCADE,
    current_instance_id UUID REFERENCES world_instances(id) ON DELETE SET NULL,
    name VARCHAR(12) NOT NULL,
    race_id SMALLINT NOT NULL,
    class_id SMALLINT NOT NULL,
    gender SMALLINT NOT NULL DEFAULT 0,
    skin SMALLINT NOT NULL DEFAULT 0,
    face SMALLINT NOT NULL DEFAULT 0,
    hair_style SMALLINT NOT NULL DEFAULT 0,
    hair_color SMALLINT NOT NULL DEFAULT 0,
    facial_hair SMALLINT NOT NULL DEFAULT 0,
    outfit_id SMALLINT NOT NULL DEFAULT 0,
    level SMALLINT NOT NULL DEFAULT 1,
    position_x REAL NOT NULL DEFAULT 0,
    position_y REAL NOT NULL DEFAULT 0,
    position_z REAL NOT NULL DEFAULT 0,
    orientation REAL NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT characters_guid_range CHECK (guid >= 1 AND guid <= 4294967295),
    CONSTRAINT characters_name_format CHECK (name ~ '^[A-Z][a-z]{1,11}$'),
    CONSTRAINT characters_realm_name_unique UNIQUE (realm_id, name),
    CONSTRAINT characters_gender_range CHECK (gender >= 0 AND gender <= 1),
    CONSTRAINT characters_appearance_ranges CHECK (
        skin >= 0 AND skin <= 255 AND
        face >= 0 AND face <= 255 AND
        hair_style >= 0 AND hair_style <= 255 AND
        hair_color >= 0 AND hair_color <= 255 AND
        facial_hair >= 0 AND facial_hair <= 255 AND
        outfit_id >= 0 AND outfit_id <= 255),
    CONSTRAINT characters_level_range CHECK (level >= 1 AND level <= 80)
);

CREATE UNIQUE INDEX characters_guid_unique ON characters (guid);
CREATE INDEX characters_account_realm_idx ON characters (account_id, realm_id);

CREATE TABLE character_equipment (
    character_id UUID NOT NULL REFERENCES characters(id) ON DELETE CASCADE,
    slot SMALLINT NOT NULL,
    item_entry INTEGER NOT NULL,
    enchant_id INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT character_equipment_pkey PRIMARY KEY (character_id, slot),
    CONSTRAINT character_equipment_slot_range CHECK (slot >= 0 AND slot <= 18),
    CONSTRAINT character_equipment_entry_positive CHECK (item_entry > 0),
    CONSTRAINT character_equipment_enchant_nonneg CHECK (enchant_id >= 0)
);

CREATE INDEX character_equipment_character_idx ON character_equipment (character_id);
